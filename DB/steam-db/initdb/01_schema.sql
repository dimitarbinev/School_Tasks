CREATE TABLE companies (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE genres (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE games (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE game_details (
    game_id integer PRIMARY KEY REFERENCES games(id) ON DELETE CASCADE,
    price numeric(8, 2) NOT NULL CHECK (price >= 0),
    release_date date,
    description text
);

CREATE TABLE game_companies (
    game_id integer NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    company_id integer NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('developer', 'publisher')),
    PRIMARY KEY (game_id, company_id, role)
);

CREATE TABLE game_genres (
    game_id integer NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    genre_id integer NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
    PRIMARY KEY (game_id, genre_id)
);

CREATE TABLE library (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    game_id integer NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    purchased_at timestamp NOT NULL,
    hours_played numeric(7, 2) NOT NULL DEFAULT 0 CHECK (hours_played >= 0),
    UNIQUE (user_id, game_id)
);

CREATE TABLE achievements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    game_id integer NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    UNIQUE (game_id, name),
    UNIQUE (id, game_id)
);

CREATE TABLE user_achievements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    achievement_id integer NOT NULL,
    unlocked_at timestamp NOT NULL,
    UNIQUE (user_id, achievement_id),
    FOREIGN KEY (achievement_id) REFERENCES achievements(id) ON DELETE CASCADE
);

CREATE TABLE reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    game_id integer NOT NULL,
    rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    text text NOT NULL,
    UNIQUE (user_id, game_id),
    FOREIGN KEY (user_id, game_id)
        REFERENCES library(user_id, game_id) ON DELETE CASCADE
);

CREATE INDEX library_game_id_idx ON library(game_id);
CREATE INDEX game_companies_company_id_idx ON game_companies(company_id);
CREATE INDEX game_genres_genre_id_idx ON game_genres(genre_id);
CREATE INDEX achievements_game_id_idx ON achievements(game_id);
CREATE INDEX user_achievements_achievement_id_idx ON user_achievements(achievement_id);
CREATE INDEX reviews_game_id_idx ON reviews(game_id);
